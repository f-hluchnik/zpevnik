"""Unit tests for the include list.

Run from the repository root: python3 -m unittest discover -s tools
"""
import unittest

from build_version import UNKNOWN_PATCH
from generate import generated_files, include_tex, version
from paths import ARTIST_PART_TEX, ARTISTS_TEX, INCLUDE_TEX, LETTERS_TEX, VERSION_TEX
from songs import Song


def song(song_id: str, title: str) -> Song:
    return Song(song_id, title, None)


class IncludeTex(unittest.TestCase):
    def test_one_songinclude_per_song_in_collation_order(self):
        tex = include_tex([song("beta", "Beta"), song("alfa", "Alfa")])
        lines = [line for line in tex.splitlines() if line.startswith("\\")]
        self.assertEqual(lines, ["\\songinclude{alfa}", "\\songinclude{beta}"])

    def test_each_first_pass_letter_gets_a_comment(self):
        tex = include_tex([song("beta", "Beta"), song("alfa", "Alfa")])
        self.assertIn("%A\n\\songinclude{alfa}\n\n%B\n\\songinclude{beta}\n", tex)

    def test_song_files_are_not_included_directly(self):
        self.assertNotIn("\\include{", include_tex([song("alfa", "Alfa")]))


class Version(unittest.TestCase):
    def test_song_count_plus_100_as_major_minor_then_the_patch(self):
        self.assertEqual(version(733, "7"), "8.33.7")
        self.assertEqual(version(700, "0"), "8.00.0")
        self.assertEqual(version(0, "12"), "1.00.12")

    def test_unknown_patch_is_visibly_incomplete(self):
        self.assertEqual(version(733, UNKNOWN_PATCH), "8.33.?")


class GeneratedFiles(unittest.TestCase):
    def test_every_output_is_produced_with_the_same_song_count(self):
        files = generated_files([{"slug": "abba", "name": "ABBA"}], [song("alfa", "Alfa")], "3")
        self.assertEqual(set(files), {ARTISTS_TEX, INCLUDE_TEX, LETTERS_TEX, ARTIST_PART_TEX, VERSION_TEX})
        self.assertIn("\\zpregisterartist{abba}{ABBA}{1}\n", files[ARTISTS_TEX])
        self.assertIn("\\renewcommand{\\zpversion}{1.01.3}", files[VERSION_TEX])
        self.assertTrue(all(text.startswith("% GENERATED by tools/generate.py") for text in files.values()))


if __name__ == "__main__":
    unittest.main()
