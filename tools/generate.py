#!/usr/bin/env python3
"""Generate the TeX files derived from the registry (D-104, ticket R5).

Reads data/artists.toml and writes generated/artists.tex: one
\\zpregisterartist{slug}{name}{index label}{1 or 0} line per entry, which
zpevnik.sty turns into lookups by slug. Generated files are build outputs
(gitignored); `make` runs this before compiling.

Usage: python3 tools/generate.py [repo-root]
Python >= 3.11, standard library only.
"""
import sys
import tomllib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from check_registry import check_entries  # noqa: E402

HEADER = "% GENERATED by tools/generate.py from data/artists.toml - do not edit.\n"
TEX_ESCAPES = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
    "\u00a0": "~",  # a non-breaking space in the registry is a tie in TeX
}


def tex(text: str) -> str:
    return "".join(TEX_ESCAPES.get(ch, ch) for ch in text)


def artists_tex(entries: list[dict]) -> str:
    lines = [HEADER]
    for e in entries:
        lines.append(
            "\\zpregisterartist{%s}{%s}{%s}{%d}\n"
            % (e["slug"], tex(e["name"]), tex(e["index_label"]), 1 if e["section"] else 0)
        )
    return "".join(lines)


def main() -> int:
    root = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent
    with open(root / "data" / "artists.toml", "rb") as f:
        entries = tomllib.load(f).get("entry", [])
    errors, _ = check_entries(entries)
    if errors:
        print("data/artists.toml is invalid:", *errors, sep="\n  ", file=sys.stderr)
        return 1

    out = root / "generated"
    out.mkdir(exist_ok=True)
    (out / "artists.tex").write_text(artists_tex(entries), encoding="utf-8")
    print(f"generated/artists.tex: {len(entries)} entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
